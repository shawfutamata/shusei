// db/data.ts に置くと、画面から読んだときにサーバーの中身まで持っていくので、
// 数字だけをここに分けてある。

/**
 * メッセージに付けた画像を預かる日数。
 *
 * **短くしてあるのは、置き場の広さを一定に保つため。** やり取りの画像は
 * 増え続ける一方で、古いものはまず見返されない。30日あれば、その場の用は足りる。
 *
 * 実体を消すのは**R2側の自動削除**（Cloudflareの画面で設定するライフサイクル
 * ルール）。コードからは設定できないので、こちらは「期限を過ぎたら出さない」
 * ところまでを受け持つ。設定を忘れていても会員には期限切れに見え、
 * 設定してあれば実体も消える。
 */
export const MESSAGE_IMAGE_DAYS = 30;

/** 1枚の上限。端末で長辺1400pxのJPEGに焼き直してから送るので、ここは歯止め。 */
export const MESSAGE_IMAGE_MAX_BYTES = 1_500_000;
